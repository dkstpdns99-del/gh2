export function calculateScores(responses: Record<number, number>) {
  const rawScores: Record<string, number> = {
    TF: 0, GM: 0, AU: 0, SE: 0,
    EC: 0, SV: 0, CH: 0, LS: 0
  };

  QUESTIONS.forEach(q => {
    const rating = responses[q.id] || 0;
    rawScores[q.anchorCode] = (rawScores[q.anchorCode] || 0) + rating;
  });

  // Max raw score per anchor = 5 questions * 4 = 20 points
  // Scale to 100 percentage points: (raw / 20) * 100
  const scaledScores: Record<string, number> = {
    TF: Math.round(((rawScores.TF || 0) / 20) * 100),
    GM: Math.round(((rawScores.GM || 0) / 20) * 100),
    AU: Math.round(((rawScores.AU || 0) / 20) * 100),
    SE: Math.round(((rawScores.SE || 0) / 20) * 100),
    EC: Math.round(((rawScores.EC || 0) / 20) * 100),
    SV: Math.round(((rawScores.SV || 0) / 20) * 100),
    CH: Math.round(((rawScores.CH || 0) / 20) * 100),
    LS: Math.round(((rawScores.LS || 0) / 20) * 100),
  };

  return { rawScores, scaledScores };
}
